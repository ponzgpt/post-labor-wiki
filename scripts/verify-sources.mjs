#!/usr/bin/env node
// Online check: DOIs resolve on Crossref with the year we cite; URLs answer. Writes research/verification.md.
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const root = new URL('..', import.meta.url).pathname;
const sources = JSON.parse(readFileSync(join(root, 'research/sources.json'), 'utf8'));
const UA = 'post-labor-wiki source verifier (https://github.com/ponzgpt/post-labor-wiki)';

async function checkDoi(s) {
  const r = await fetch(`https://api.crossref.org/works/${encodeURIComponent(s.doi)}`, { headers: { 'User-Agent': UA } });
  if (!r.ok) return ['fail', `Crossref ${r.status}`];
  const m = (await r.json()).message;
  // Journals often publish online a year before print; either year counts.
  const years = ['issued', 'published-print', 'published-online'].map((k) => m[k]?.['date-parts']?.[0]?.[0]);
  return years.includes(s.year) ? ['ok', `Crossref: ${m.title?.[0]}`] : ['warn', `Crossref years ${years.filter(Boolean)} ≠ ${s.year}`];
}

async function checkUrl(s) {
  const r = await fetch(s.url, { headers: { 'User-Agent': 'Mozilla/5.0' }, redirect: 'follow', signal: AbortSignal.timeout(20000) });
  if (r.ok) return ['ok', `HTTP ${r.status}`];
  // Publishers and some agencies wall off non-browser clients; those need a human click, not a fix.
  return [[401, 403, 429].includes(r.status) ? 'warn' : 'fail', `HTTP ${r.status}`];
}

const rows = [];
for (const s of sources) {
  await new Promise((r) => setTimeout(r, 1500)); // Open Library refuses bursts
  let res;
  try { res = await (s.doi ? checkDoi(s) : checkUrl(s)); } catch (e) { res = ['warn', `network: ${e.cause?.code ?? e.name}`]; }
  rows.push([s.id, ...res]);
  console.log(res[0].padEnd(4), s.id, res[1]);
}

const n = (k) => rows.filter((r) => r[1] === k).length;
const date = new Date().toISOString().slice(0, 10);
writeFileSync(join(root, 'research/verification.md'),
  `# Source verification (${date})\n\nGenerated by \`npm run verify\`. ok ${n('ok')} · warn ${n('warn')} (bot wall or year mismatch: check by hand) · fail ${n('fail')}\n\n| id | status | detail |\n|---|---|---|\n` +
  rows.map((r) => `| ${r[0]} | ${r[1]} | ${r[2].replaceAll('|', '/')} |`).join('\n') + '\n');
process.exit(n('fail') ? 1 : 0);
